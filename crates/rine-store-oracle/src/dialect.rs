//! [`Dialect`] abstracts the per-database SQL (`:1` vs `?` placeholders,
//! DDL, a few functions); the MVCC logic in `SqlBackend` is shared.
//! Placeholder style is covered by unit tests below; the live XE test in CI
//! covers Oracle against a real database.

use rine_store_executor::Dialect;

/// Oracle DDL for the `rine` table.
///
/// `value` is a BLOB: the official `oracledb` driver handles temporary LOBs
/// (bind + inline fetch) natively, so no LONG RAW workaround is needed.
const CREATE_TABLE: &str = r#"
CREATE TABLE rine (
    id NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    name VARCHAR2(630),
    created NUMBER DEFAULT 0,
    deleted NUMBER DEFAULT 0,
    create_revision NUMBER DEFAULT 0,
    prev_revision NUMBER DEFAULT 0,
    lease NUMBER DEFAULT 0,
    version NUMBER DEFAULT 1,
    value BLOB
)
"#;

const CREATE_INDEXES: &[&str] = &[
    "CREATE INDEX rine_name_index ON rine(name)",
    "CREATE INDEX rine_name_id_index ON rine(name, id)",
    "CREATE INDEX rine_id_deleted_index ON rine(id, deleted)",
    "CREATE INDEX rine_prev_revision_index ON rine(prev_revision)",
    "CREATE UNIQUE INDEX rine_name_prev_revision_index ON rine(name, prev_revision)",
];

/// Oracle SQL dialect. Named bind style (`:1`, `:2`, ...).
pub struct OracleDialect;

impl Dialect for OracleDialect {
    fn create_table_sql() -> &'static str {
        CREATE_TABLE
    }

    fn create_indexes_sql() -> &'static [&'static str] {
        CREATE_INDEXES
    }

    fn probe_sql() -> &'static str {
        "SELECT 1 FROM rine WHERE ROWNUM = 1"
    }

    fn current_revision_sql() -> String {
        "SELECT created FROM rine ORDER BY id DESC FETCH FIRST 1 ROWS ONLY".into()
    }

    fn bind(index: usize) -> String {
        format!(":{index}")
    }

    fn events_sql() -> String {
        format!(
            "SELECT {COLS} FROM rine WHERE created >= :1 AND created <= :2 AND name <> 'compact_rev_key' ORDER BY id",
            COLS = Self::cols(),
        )
    }

    fn set_deleted_by_id_sql() -> &'static str {
        "UPDATE rine SET deleted = :1 WHERE id = :2 AND deleted = 0"
    }

    fn compact_delete_sql() -> &'static str {
        "DELETE FROM rine WHERE id IN (SELECT id FROM rine WHERE created < :1 AND name <> 'compact_rev_key' \
         AND id NOT IN (SELECT MAX(id) FROM rine WHERE created <= :2 GROUP BY name) FETCH FIRST :3 ROWS ONLY)"
    }

    fn set_compact_rev_sql() -> &'static str {
        "UPDATE rine SET prev_revision = :1 WHERE name = 'compact_rev_key'"
    }

    fn set_compact_rev_insert_sql() -> &'static str {
        "INSERT INTO rine (id, name, created, deleted, create_revision, prev_revision, lease) \
         VALUES (0, 'compact_rev_key', 0, 0, 0, :1, 0)"
    }

    fn row_limit(bind: usize) -> String {
        format!(" FETCH FIRST {} ROWS ONLY", Self::bind(bind))
    }

    fn commit_state_sql(names: usize) -> String {
        // Callers chunk names to `COMMIT_NAMES_PER_QUERY`, so no IN-list cap
        // handling here.
        let meta = "SELECT created, id FROM rine ORDER BY id DESC FETCH FIRST 1 ROWS ONLY";
        let header = "GREATEST(NVL(m.created, 1), 1), GREATEST(NVL(m.id, 1), 1)";
        if names == 0 {
            return format!("SELECT {header}, NULL FROM dual LEFT JOIN ({meta}) m ON 1=1");
        }
        let binds = (1..=names).map(Self::bind).collect::<Vec<_>>().join(", ");
        format!(
            "SELECT {header}, k.name, k.key_id, k.live_revision FROM dual \
             LEFT JOIN ({meta}) m ON 1=1 \
             LEFT JOIN (SELECT name, NVL(MAX(CASE WHEN deleted = 0 THEN id END), MAX(id)) AS key_id, \
                  MAX(CASE WHEN deleted = 0 THEN created END) AS live_revision \
                  FROM rine WHERE name IN ({binds}) GROUP BY name) k ON 1=1"
        )
    }

    /// Allocated segment bytes for our tables, indexes, and LOB storage:
    /// one data-dictionary lookup, O(1) in table size. `LIKE 'RINE%'`
    /// covers the `rine`/`rine_leases` tables plus their indexes; out-of-line
    /// BLOB bytes live in system-named LOB segments resolved via `user_lobs`.
    fn db_size_sql() -> &'static str {
        "SELECT NVL(SUM(s.bytes), 0) FROM user_segments s WHERE s.segment_name LIKE 'RINE%' \
          OR s.segment_name IN (SELECT l.segment_name FROM user_lobs l WHERE l.table_name LIKE 'RINE%')"
    }

    fn create_leases_table_sql() -> &'static str {
        "CREATE TABLE rine_leases (\
            id NUMBER PRIMARY KEY, \
            granted_ttl NUMBER DEFAULT 0, \
            expires_at_ms NUMBER DEFAULT 0, \
            keys BLOB\
        )"
    }

    fn leases_probe_sql() -> &'static str {
        "SELECT 1 FROM rine_leases WHERE ROWNUM = 1"
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use rine_etcd::backend::ListOptions;

    #[test]
    fn binds_are_oracle_style() {
        let (rows, count) = OracleDialect::live_range_queries(
            Some(b"x"),
            &ListOptions {
                limit: 10,
                ..Default::default()
            },
        );
        let owned = [
            OracleDialect::list_history_sql(Some(b"x")),
            OracleDialect::commit_state_sql(2),
            OracleDialect::events_sql(),
            rows.unwrap(),
            count.unwrap(),
            OracleDialect::lease_update_sql(),
            OracleDialect::lease_insert_sql(),
            OracleDialect::lease_select_sql(),
            OracleDialect::lease_delete_sql(),
            OracleDialect::lease_expired_select_sql(),
            OracleDialect::lease_expired_delete_sql(),
        ];
        for sql in owned.iter().map(String::as_str).chain([
            OracleDialect::set_compact_rev_sql(),
            OracleDialect::set_compact_rev_insert_sql(),
            OracleDialect::compact_delete_sql(),
            OracleDialect::set_deleted_by_id_sql(),
        ]) {
            assert!(sql.contains(":1"), "{sql}");
            assert!(!sql.contains('?'), "{sql}");
        }
    }
}
